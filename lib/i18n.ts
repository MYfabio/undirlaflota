export const DICTS: Record<Lang, Dict> = { ca, es, en };

export function isLang(x: unknown): x is Lang {
  return x === "ca" || x === "es" || x === "en";
}

/** Tradueix una clau amb substitució de {placeholders}. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.ca[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Detecta l'idioma del navegador (client). */
export function detectLang(): Lang {
  if (typeof navigator === "undefined") return DEFAULT_LANG;
  const n = navigator.language.toLowerCase();
  if (n.startsWith("ca")) return "ca";
  if (n.startsWith("es")) return "es";
  if (n.startsWith("en")) return "en";
  return DEFAULT_LANG;
}
